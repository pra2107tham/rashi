export type StringKey = keyof typeof strings;

export function t(key: StringKey, lang: Language): string {
  return strings[key][lang];
}

export const other = (lang: Language): Language => (lang === "hi" ? "en" : "hi");

/** `tr(key)` in the user's language; `alt(key)` in the other one; `both(key)` → "Primary · Other". */
export function useT() {
  const lang = useApp((s) => s.language) ?? "en";
  return {
    lang,
    tr: (key: StringKey) => strings[key][lang],
    alt: (key: StringKey) => strings[key][other(lang)],
    both: (key: StringKey) => `${strings[key][lang]} · ${strings[key][other(lang)]}`,
  };
}
